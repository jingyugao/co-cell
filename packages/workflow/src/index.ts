import { z } from 'zod';

export const taskKey = z.string().regex(/^[a-z][a-z0-9_-]{0,47}$/);
const text = z.string().trim().min(1).max(6000);
const paths = z
  .array(z.string().min(1).max(250))
  .max(64)
  .describe(
    'Exact normalized project-relative file or directory names, e.g. src/a.ts. No prose, absolute paths, dot, globs, or dot-dot. Use [] for none.'
  );
export const checkSchema = z.strictObject({
  argv: z.array(z.string().min(1).max(2000)).min(1).max(48),
  cwd: z
    .string()
    .min(1)
    .max(250)
    .describe('Use . for project root, otherwise a canonical project-relative directory.'),
  outputPaths: paths.describe(
    'Only file paths generated by the validation command; [] when the command writes nothing.'
  ),
  timeoutMs: z.number().int().min(1000).max(300000),
});
export const taskSchema = z.strictObject({
  key: taskKey,
  role: z.enum(['worker', 'integration', 'verifier']),
  description: text,
  dependsOn: z.array(taskKey).max(32),
  ownedPaths: paths,
  readPaths: paths,
  acceptance: text,
  validation: checkSchema,
});
export const planSchema = z.strictObject({
  design: text,
  alternatives: text,
  publicContracts: paths.describe(
    'Paths of shared interface files reserved for integration. Use [] when there are none. Describe behavioral contracts in design instead.'
  ),
  risks: text,
  reviewDecisions: text,
  tasks: z.array(taskSchema).min(3).max(32),
});
export const modulePlanSchema = planSchema.extend({
  tasks: z.array(taskSchema.extend({
    title: z.string().trim().min(1).max(80).describe('Short user-facing name of the deliverable in the language of the requirement.'),
  })).min(3).max(32),
});
export const resultSchema = z.strictObject({
  summary: text,
  evidence: z.array(text).max(16),
  concerns: z.array(text).max(12),
  needsDecision: z.boolean(),
  passed: z.boolean(),
});
export type PlanTask = z.infer<typeof taskSchema> & { title?: string };
export type Plan = Omit<z.infer<typeof planSchema>, 'tasks'> & { tasks: PlanTask[] };
export type Check = z.infer<typeof checkSchema>;
export type Finding = z.infer<typeof resultSchema>;
export const overlaps = (a: string, b: string) => a === b || a.startsWith(b + '/') || b.startsWith(a + '/');
export const within = (path: string, root: string) => path === root || path.startsWith(root + '/');
export function validPath(path: string) {
  return (
    !/[\\\x00-\x1f:*?"<>|]/.test(path) &&
    path.split('/').every((p) => p && !['.', '..', '.git', '.cocell', 'node_modules'].includes(p))
  );
}

export function validatePlan(value: unknown, mode?: 'modules' | 'reviewed'): Plan {
  const plan = (mode === 'modules' ? modulePlanSchema : planSchema).parse(value);
  const tasks = new Map(plan.tasks.map((t) => [t.key, t]));
  if (tasks.size !== plan.tasks.length) throw Error('任务 key 必须唯一');
  const ancestors = new Map<string, Set<string>>();
  function visit(key: string, visiting: Set<string>): Set<string> {
    const previous = ancestors.get(key);
    if (previous) return previous;
    const task = tasks.get(key);
    if (!task || visiting.has(key)) throw Error('任务依赖缺失或成环：' + key);
    const seen = new Set<string>();
    for (const dep of task.dependsOn) {
      seen.add(dep);
      for (const ancestor of visit(dep, new Set([...visiting, key]))) seen.add(ancestor);
    }
    ancestors.set(key, seen);
    return seen;
  }
  const integrations = plan.tasks.filter((t) => t.role === 'integration');
  const verifiers = plan.tasks.filter((t) => t.role === 'verifier');
  const integration = integrations[0],
    verifier = verifiers[0];
  if (integrations.length !== 1 || verifiers.length !== 1) throw Error('计划须包含一个集成任务和一个最终验证任务');
  for (const task of plan.tasks) {
    visit(task.key, new Set());
    for (const [field, values] of Object.entries({
      ownedPaths: task.ownedPaths,
      readPaths: task.readPaths,
      outputPaths: task.validation.outputPaths,
      publicContracts: plan.publicContracts,
      cwd: task.validation.cwd === '.' ? [] : [task.validation.cwd],
    })) {
      const invalid = values.find((path) => !validPath(path));
      if (invalid !== undefined)
        throw Error(task.key + '.' + field + ' 包含无效项目路径 ' + JSON.stringify(invalid));
    }
    if (task.validation.argv.some((arg) => arg.includes('\0'))) throw Error('验证参数包含空字符');
    if (task.role === 'worker' && !task.ownedPaths.length) throw Error('实施任务必须声明写入范围');
    if (task.role === 'verifier' && task.ownedPaths.length) throw Error('最终验证 agent 必须只读');
    if (task.role === 'worker' && task.ownedPaths.some((p) => plan.publicContracts.some((c) => overlaps(p, c))))
      throw Error('公共契约只能归集成任务写入');
    if (task.role === 'worker' && !visit(integration.key, new Set()).has(task.key))
      throw Error('集成必须依赖所有实施任务');
    if (!visit(verifier.key, new Set()).has(integration.key)) throw Error('最终验证必须依赖集成');
    const [exe, ...args] = task.validation.argv;
    if (
      !/^[A-Za-z0-9_./+-]+$/.test(exe) ||
      /^(git|gh|glab|kubectl|helm|docker|ssh|scp|sudo|sh|bash|zsh|fish|env|eval|exec)$/.test(
        exe.split('/').at(-1)!
      ) ||
      args.includes('publish') ||
      args.includes('deploy')
    )
      throw Error('验证命令须使用直接的项目检查程序');
    for (const other of plan.tasks) {
      if (
        other.key === task.key ||
        visit(task.key, new Set()).has(other.key) ||
        visit(other.key, new Set()).has(task.key)
      )
        continue;
      if (task.ownedPaths.some((p) => [...other.ownedPaths, ...other.readPaths].some((q) => overlaps(p, q))))
        throw Error('并行任务读写范围冲突：' + task.key + ' / ' + other.key);
    }
  }
  return plan;
}

